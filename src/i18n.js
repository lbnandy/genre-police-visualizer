  function normalizeLocale(value, fallback = DEFAULT_LOCALE) {
    const locale = String(value || '').trim().toLowerCase().replace('_', '-');
    if (locale === 'ja' || locale.startsWith('ja-') || locale === 'jp') return 'ja';
    if (locale === 'ko' || locale.startsWith('ko-') || locale === 'kr') return 'ko';
    if (locale === 'en' || locale.startsWith('en-')) return 'en';
    if (locale === 'zh' || locale.startsWith('zh-')) return 'zh-CN';
    return SUPPORTED_LOCALES.includes(fallback) ? fallback : DEFAULT_LOCALE;
  }

  function translate(locale, key, variables = {}) {
    const normalized = normalizeLocale(locale);
    const template = messages[normalized]?.[key] ?? messages[DEFAULT_LOCALE]?.[key] ?? key;
    return String(template).replace(/\{([A-Za-z0-9_]+)\}/g, (match, name) => (
      Object.hasOwn(variables, name) ? String(variables[name]) : match
    ));
  }

  return Object.freeze({ DEFAULT_LOCALE, SUPPORTED_LOCALES, messages, normalizeLocale, translate });
